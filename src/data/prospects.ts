export function weeklyProspects(now = new Date()) {
  const start = new Date(now.getFullYear(), 0, 1)
  const week = Math.floor((now.getTime() - start.getTime()) / (7 * 24 * 3600 * 1000))
  const rotating = prospects.filter((item) => !item.alwaysOn)
  const always = prospects.filter((item) => item.alwaysOn)
  const pick = rotating
    .map((item, index) => rotating[(index + week) % rotating.length])
    .slice(0, 5)
  const seen = new Set<string>()
  return [...always, ...pick].filter((item) => {
    if (seen.has(item.id)) return false
    seen.add(item.id)
    return true
  })
}
